/// <reference types="node" />
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const CHECK = process.argv.includes("--check");

type GeneratedFile = { path: string; content: string };

const MARKER = "// Generated by scripts/gen.ts — do not edit.";

const ABIS: ReadonlyArray<readonly [module: string, source: string, exportName: string]> = [
  ["identity", "IdentityRegistry.json", "identityRegistryAbi"],
  ["reputation", "ReputationRegistry.json", "reputationRegistryAbi"],
  ["validation", "ValidationRegistry.json", "validationRegistryAbi"],
];

function readData(path: string): unknown {
  return JSON.parse(readFileSync(join(ROOT, "data", path), "utf8"));
}

const PROTOCOL_EVENTS: Record<string, ReadonlyArray<string>> = {
  identity: [
    "Registered",
    "URIUpdated",
    "MetadataSet",
    "Transfer",
    "Approval",
    "ApprovalForAll",
    "MetadataUpdate",
    "BatchMetadataUpdate",
  ],
  reputation: ["NewFeedback", "FeedbackRevoked", "ResponseAppended"],
  validation: ["ValidationRequest", "ValidationResponse"],
};

function abiModules(): GeneratedFile[] {
  const events: unknown[] = [];
  for (const [module, source] of ABIS) {
    const names = new Set(PROTOCOL_EVENTS[module]);
    const abi = readData(join("abis", source));
    if (!Array.isArray(abi)) {
      throw new TypeError(`data/abis/${source}: expected a JSON array`);
    }
    for (const entry of abi) {
      if (isRecord(entry) && entry["type"] === "event" && names.has(entry["name"] as string)) {
        events.push(entry);
      }
    }
    for (const name of names) {
      if (!events.some((e) => isRecord(e) && e["name"] === name)) {
        throw new Error(`data/abis/${source}: protocol event ${name} missing`);
      }
    }
  }
  const modules = ABIS.map(([module, source, exportName]) => ({
    path: join("packages/erc8004/src/abi", `${module}.ts`),
    content:
      `${MARKER}\n` +
      `// Source: data/abis/${source} (see data/SOURCE.md).\n` +
      `export const ${exportName} = ${JSON.stringify(readData(join("abis", source)), null, 2)} as const;\n`,
  }));
  const index = ABIS.map(
    ([module, , exportName]) => `export { ${exportName} } from "./${module}.ts";`,
  ).join("\n");
  modules.push(
    {
      path: "packages/erc8004/src/abi/index.ts",
      content: `${MARKER}\n${index}\nexport { protocolEventsAbi } from "./protocol-events.ts";\n`,
    },
    {
      path: "packages/erc8004/src/abi/protocol-events.ts",
      content:
        `${MARKER}\n` +
        `// Source: data/abis/*.json — the 13 protocol events only (admin events excluded).\n` +
        `export const protocolEventsAbi = ${JSON.stringify(events, null, 2)} as const;\n`,
    },
  );
  return modules;
}

function camelCase(id: string): string {
  return id.replaceAll(/-[a-z0-9]/g, (pair) => pair.slice(1).toUpperCase());
}

function objectKey(id: string): string {
  const key = camelCase(id);
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

type Deployment = {
  id: string;
  name: string;
  chainId: number;
  testnet: boolean;
  identityRegistry: string;
  reputationRegistry: string;
  validationRegistry: string;
};

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

const ADDRESS_FIELDS = ["identityRegistry", "reputationRegistry", "validationRegistry"];

function isDeployment(value: unknown): value is Deployment {
  return (
    isRecord(value) &&
    typeof value["id"] === "string" &&
    typeof value["name"] === "string" &&
    typeof value["chainId"] === "number" &&
    typeof value["testnet"] === "boolean" &&
    ADDRESS_FIELDS.every((field) => typeof value[field] === "string")
  );
}

function deploymentsModule(): GeneratedFile {
  const data = readData("deployments.json");
  const raw = isRecord(data) ? data["deployments"] : undefined;
  const deployments = Array.isArray(raw) ? raw.filter(isDeployment) : [];
  if (!Array.isArray(raw) || deployments.length !== raw.length) {
    throw new Error("data/deployments.json: deployments must be an array of Deployment objects");
  }
  const entries = deployments
    .map((d) => `${objectKey(d.id)}: ${JSON.stringify(d, null, 2)},`)
    .join("\n");
  const keys = deployments.map((d) => JSON.stringify(camelCase(d.id))).join(" | ");
  return {
    path: "packages/erc8004/src/deployments/data.ts",
    content:
      `${MARKER}\n` +
      `// Source: data/deployments.json.\n` +
      `import type { Deployment } from "./deployment.ts";\n\n` +
      `type DeploymentKey = ${keys};\n\n` +
      `export const deployments: Readonly<Record<DeploymentKey, Deployment>> = {\n${entries}\n};\n`,
  };
}

function screamingSnake(id: string): string {
  return id.replaceAll("-", "_").toUpperCase();
}

function rustDeploymentsModule(): GeneratedFile {
  const data = readData("deployments.json");
  const raw = isRecord(data) ? data["deployments"] : undefined;
  const deployments = Array.isArray(raw) ? raw.filter(isDeployment) : [];
  if (!Array.isArray(raw) || deployments.length !== raw.length) {
    throw new Error("data/deployments.json: deployments must be an array of Deployment objects");
  }
  const consts = deployments
    .map(
      (d) => `/// \`${d.name}\`.
pub const ${screamingSnake(d.id)}: Deployment = Deployment {
    id: "${d.id}",
    name: ${JSON.stringify(d.name)},
    chain_id: ${d.chainId.toLocaleString("en-US").replaceAll(",", "_")},
    testnet: ${d.testnet ? "true" : "false"},
    identity_registry: address!("${d.identityRegistry.slice(2)}"),
    reputation_registry: address!("${d.reputationRegistry.slice(2)}"),
    validation_registry: address!("${d.validationRegistry.slice(2)}"),
};`,
    )
    .join("\n\n");
  const names = deployments.map((d) => screamingSnake(d.id)).join(", ");
  return {
    path: "crates/erc8004/src/deployments/data.rs",
    content:
      `//! Generated by scripts/gen.ts — do not edit.
` +
      `//! Source: data/deployments.json.
` +
      `use alloy::primitives::address;

` +
      `use super::Deployment;

` +
      `${consts}

` +
      `/// Every verified deployment, mainnets first then by chain id.
` +
      `pub const ALL: &[Deployment] = &[${names}];
`,
  };
}

// TypeScript files go through `vp fmt`, Rust through `rustfmt --edition 2024`
// on stdin, so generated output is already formatted and `bun run gen --check`
// agrees with `vp check` / `cargo fmt --check`.
function format(path: string, content: string): string {
  const env = {
    ...process.env,
    PATH: `${join(ROOT, "node_modules/.bin")}:${process.env["PATH"] ?? ""}`,
  };
  if (path.endsWith(".rs")) {
    const out = spawnSync("rustfmt", ["--edition", "2024"], {
      cwd: ROOT,
      env,
      input: content,
      encoding: "utf8",
    });
    if (out.status !== 0 || out.stdout === "") {
      throw new Error(`rustfmt failed for ${path}: ${out.stderr}`);
    }
    return out.stdout;
  }
  if (!path.endsWith(".ts")) {
    return content;
  }
  const out = spawnSync("vp", ["fmt", `--stdin-filepath=${path}`], {
    cwd: ROOT,
    env,
    input: content,
    encoding: "utf8",
  });
  if (out.status !== 0 || out.stdout === "") {
    throw new Error(`vp fmt failed for ${path}: ${out.stderr}`);
  }
  return out.stdout;
}

if (import.meta.main) {
  const targets: GeneratedFile[] = [...abiModules(), deploymentsModule(), rustDeploymentsModule()];
  let drift = false;
  for (const { path, content } of targets) {
    const formatted = format(path, content);
    const full = join(ROOT, path);
    const current = (() => {
      try {
        return readFileSync(full, "utf8");
      } catch {
        return "";
      }
    })();
    if (CHECK) {
      if (current !== formatted) {
        console.error(`gen: ${path} is out of date`);
        drift = true;
      }
    } else if (current !== formatted) {
      writeFileSync(full, formatted);
      console.log(`gen: wrote ${path}`);
    }
  }
  if (drift) {
    console.error("gen: run `bun run gen` to regenerate");
    process.exitCode = 1;
  }
}
